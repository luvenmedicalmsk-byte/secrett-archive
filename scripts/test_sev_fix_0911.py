#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""SEV_FIX_0911. Запуск: python scripts/test_sev_fix_0911.py"""
import sys, io, os, contextlib
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
with contextlib.redirect_stderr(io.StringIO()):
    import fetch_events as fe
fails = []
def ok(c, m):
    if not c: fails.append(m)
def run(t, sev, dom='geopolitics', summary=''):
    x = [{'title': t, 'summary': summary, 'severity': sev, 'domain': dom, 'source': 'X'}]
    with contextlib.redirect_stderr(io.StringIO()):
        fe._sev_post_hyg_0511(x)
    return x[0]['severity']
G = ('Израильские удары дронов, стрельба ранили 18 палестинцев — Газу',
     'Израильские нарушения прекращения огня с октября 2025 года убили 1,613 человек и ранили 5,833 других, сообщает Министерство здравоохранения Газы.')
ok(run(G[0], 92, summary=G[1]) <= 66, 'Газа: накопленный итог не задаёт индекс эпизода')
ok(run('Удар по школе в Газе: погибли 12 человек', 90, summary='С начала войны погибли более 70 000 человек.') == 90, 'эпизод с 12 погибшими не ограничивается')
ok(run('Число погибших в Газе с начала войны превысило 70 тысяч', 90) == 90, 'сам накопленный итог в заголовке - не ограничивается')
ok(run('Три человека погибли, еще 35 пострадали при обстреле военного городка в Колумбии', 95) == 82, 'Колумбия: 3 погибших, 35 пострадавших - 82')
ok(run('Два человека погибли, 60 пострадали при взрыве', 95) == 86, '2 погибших, 60 пострадавших - 86')
ok(run('Два человека погибли, 150 пострадали при землетрясении', 90) == 90, '150 пострадавших - без потолка')
ok(run('По меньшей мере 35 погибших — мигрантское судно затонуло у берегов Сенегала', 70, 'social') == 85, 'кораблекрушение 35 - 85')
ok(run('Мигрантское судно затонуло у берегов Сенегала, 21 погибший: власти', 70, 'social') == 80, 'кораблекрушение 21 - 80')
ok(run('Танкер атакован дроном в Красном море', 50) == 80, 'атака на суда в ключевом проходе - прежний пол 80')
fe.SEV_FIX_0911 = False
ok(run('Три человека погибли, еще 35 пострадали при обстреле военного городка в Колумбии', 95) == 95, 'флаг выключен - прежнее поведение')
print('SEV_FIX_0911: %s' % ('OK' if not fails else 'ОШИБКИ'))
for f in fails: print('  -', f)
sys.exit(1 if fails else 0)
