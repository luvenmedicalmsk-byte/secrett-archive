# -*- coding: utf-8 -*-
"""CONTEXT_SIGNAL_SHADOW (19.11.2026, решение Мии). Только shadow.

Контекст ленты - всё, что классификатор намерения (SIC) не отнёс к событию.
Туда попадают заявления, решения и прогнозы ведомств и официальная статистика
(«ЦБ допускает повышение ставки», «NERC: нехватка топлива для энергосети»,
«США упрутся в потолок долга в феврале 2027 года»). Модуль только помечает
такие записи полем context_signal_shadow = {signal, why}; feed_visible,
hide_reason и context_only не меняются.
"""
import re
INST = re.compile(r'(?<![А-Яа-яЁё])(ЦБ|Банк\w* России|ФРС|ЕЦБ|Банк\w* Англии|Банк\w* Японии|Нацбанк\w*|центробанк\w*|центральн\w+ банк\w*|Минфин\w*|министерств\w+|министр\w*|Еврокомисси\w+|ЕК|Совет\w* ЕС|Еврогрупп\w*|МВФ|Всемирн\w+ банк\w*|ОЭСР|ОПЕК\+?|МЭА|CBO|NERC|Казначейств\w+|Росстат\w*|правительств\w+|регулятор\w*|Конгресс\w*|Белый дом|Госдум\w*|Евростат\w*|Bundesbank|SEC|FDIC|Fed|ECB|IMF|OPEC|ЕС|Евросоюз\w*|НАТО|ВОЗ|CISA|Роспотребнадзор\w*|Минздрав\w*|Минобороны|Пентагон\w*|Сенат\w*|парламент\w*|арми\w+|ВСУ|ЦАХАЛ)(?![А-Яа-яЁё])', re.I)
DATA = re.compile(r'инфляц|инфляционн\w+ ожидан|\bCPI\b|\bPPI\b|\bPMI\b|ВВП|безработиц|дефицит\w* бюджет|госдолг|потол\w+ (?:гос)?долг|лимит\w* заимствован|ключев\w+ ставк|учётн\w+ ставк|процентн\w+ ставк|торгов\w+ баланс|платёжн\w+ баланс|резерв', re.I)
ACT = re.compile(r'\d|готовност|передаст|выделит|карантин|одобри|законопроект|ставк|санкц|пакет|потол|лимит|дефицит|инфляц|прогноз|предупрежд|ужесточ|повыш|сниж|запрет|решени|утверд|одобр|ввод|отмен|ограничен|риск|угроз|нехватк|дефицит', re.I)
LEAD = re.compile(r'(?<![А-Яа-яЁё])(Трамп\w*|Путин\w*|Си Цзиньпин\w*|Мерц\w*|Макрон\w*|Зеленск\w+|Нетаньяху|Эрдоган\w*|Стармер\w*|канцлер\w*|президент\w*|премьер\w*)(?![А-Яа-яЁё])')
LACT = re.compile(r'рассматрива\w+ (?:нов\w+ )?удар|допусти\w+ (?:отмен|сняти|введени)|приказа\w*|подписа\w*|объяви\w+ (?:о |мобилиз|режим|чрезвыч)|ввёл|ввел|утвердил|запрети\w*|пригрози\w*', re.I)
OPIN = re.compile(r'недел\w+ (?:повышения )?осведомл|аспект\w* |гендерн|интервью|мнени|колонк|блог|почему |как\s|что значит|все всегда|хорошие парни|экс-сотрудниц|эксперт\w* считают|по словам эксперт|аналитик\w* считают|^«', re.I)
def check(e):
    """Только для записей контекста (context_only). Ничего не меняет."""
    t = e.get('title') or ''; s = (e.get('summary') or '')[:300]
    if not e.get('context_only'):
        return None
    if OPIN.search(t):
        return {'signal': False, 'why': 'формат мнения или объяснения'}
    inst = INST.search(t) or INST.search(s)
    data = DATA.search(t)
    act = ACT.search(t)
    lead = LEAD.search(t) if LACT.search(t) else None
    if (inst and act) or data or lead:
        why = []
        if inst: why.append('ведомство: ' + inst.group(1))
        if data: why.append('официальный показатель: ' + data.group(0))
        if lead and not inst: why.append('решение руководителя государства: ' + lead.group(1))
        if act and inst and not data: why.append('решение, прогноз или число')
        return {'signal': True, 'why': '; '.join(why)}
    return {'signal': False, 'why': 'нет ведомства с решением, прогнозом или числом и нет официального показателя'}
