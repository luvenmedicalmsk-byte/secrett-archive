# ГЕНИТИВ ПРИ ОПОРЕ УДАРА = АКТОР, ЕСЛИ ДАЛЬШЕ ИДЁТ ЦЕЛЬ.
# «ответных ударов России по логистике» давало RU: правило рассчитано
# на «обстрел Харькова», где генитив указывает место. Здесь он указывает,
# ЧЬИ удары, а место идёт после предлога «по».
#
#   обстрел Харькова          Харьков - цель, место        ✅
#   удары России по логистике Россия - субъект, не место   ❌
_GEN_ACTOR = re.compile(
    r'(?:обстрел\w*|бомбардировк\w*|атак\w*|удар\w*|нал[её]т\w*)\s+'
    r'([а-яё\-]+)\s+по\s+', re.I)


def detect_place_v2(title, summary, others):
    """PLACE по ADR-051 + расширенное покрытие конструкций."""
    text = (title or "") + " " + (summary or "")
    tl = text.lower()
    ttl = (title or "").lower()

    # Условие 1 · физическая локализация. Проверяется ПЕРВЫМ, до всех конструкций.
    # TASK-068E · OUTAGE как самостоятельный географический класс.
    # Проверяется ДО условия 1: распределённое нарушение инфраструктуры
    # не является точечным физическим действием и через _PHYS не проходит.
    # Территория должна быть объектом outage, а не источником сообщения.
    if _OUTAGE.search(ttl):
        # источник сообщения не даёт места
        # TASK-068G · SOURCE_REPORTING vs EVENT_PREDICATE.
        # Признак — предлог «о/об/про» ПЕРЕД outage-словом: он вводит
        # содержание сообщения, а не событие. «сообщили ОБ отключении
        # в Украине» — Украина внутри содержания; «в Украине произошёл
        # блэкаут» — Украина при событийном предикате.
        _content = _OUT_CONTENT.search(ttl)
        if not (_content or _COMM_PRED.search(ttl)):
            for _m in _LOC.finditer(tl):
                _cc = _pl_resolve(_m.group(1))
                if _cc and _cc not in others and not _pl_dependent(tl, _m.start(1)):
                    return _cc, "outage-территория"
            _mc = _COLON.match((title or "").strip())
            if _mc:
                for _part in (_mc.group(2), _mc.group(1)):
                    _pl = _places_in(_part.lower())
                    if _pl and _pl[0][1][0] not in others:
                        return _pl[0][1][0], "outage-территория"
            _ma = _LOC_ACC.search(tl)
            if _ma:
                _cc = _pl_resolve(_ma.group(1))
                if _cc and _cc not in others:
                    return _cc, "outage-территория"
            # «накрыл Грузию» — винительный при outage-предикате
            _mn = re.search(r"(?:накрыл\w*|охватил\w*|затронул\w*)\s+([а-яёa-z\-]+)", tl, re.I)
            if _mn:
                _cc = _pl_resolve(_mn.group(1))
                if _cc and _cc not in others and not _is_attributive(_mn.group(1)):
                    return _cc, "outage-территория"
        return None, "outage без территории"

    if _NONPHYS.search(ttl) and not _PHYS.search(ttl):
        return None, "не физическое"
    # D-062C-2 · физичность ДЕЙСТВИЯ, а не объекта. Если предикат
    # коммуникативный, физическое слово является предметом высказывания.
    # D-062E-1 · приоритет EVENT_PLACE > WITNESS_LOCATION.
    # Свидетельство даёт место ТОЛЬКО когда место события не названо
    # отдельно: «Жители Белгорода сообщили о пожаре в Украине» —
    # пожар в UA, свидетели в RU, PLACE = UA.
    _w = _WITNESS.search((title or "").strip())
    _wloc = None
    if _w:
        _wloc = _pl_resolve(_w.group(1))
        if _wloc in others:
            _wloc = None
    if _wloc:
        # ищем место события среди локативов, исключая позицию свидетеля
        _wend = _w.end(1)
        for _mm in _LOC.finditer(tl):
            if _mm.start(1) <= _wend:
                continue                      # это сам свидетель
            _ev = _pl_resolve(_mm.group(1))
            if _ev and _ev not in others and not _pl_dependent(tl, _mm.start(1)):
                return _ev, "место события над свидетелем"
        # места события нет — свидетельство даёт место только при физичности
        if _PHYS.search(tl) or _NAT.search(tl):
            if not _COMM_ONLY.search(ttl):
                return _wloc, "свидетельство участника"
        return None, "свидетель при коммуникативном"
    if _COMM_PRED.search(ttl):
        return None, "коммуникативное о физическом"
    if not (_PHYS.search(tl) or _NAT.search(tl)):
        return None, "действие не локализовано"

    # Условие 2 · место названо. Порядок: цель → локатив → генитив → двоеточие → приложение.
    m = _TGT_P.search(tl)
    if m:
        cc = _pl_resolve(m.group(1))
        if cc and cc not in others and not _pl_dependent(tl, m.start(1)):
            return cc, "кинетическая цель"

    for m in _ADMIN_HEAD.finditer(tl):            # D-062C-1
        cc = _pl_resolve(m.group(1))
        if cc and cc not in others and not _pl_dependent(tl, m.start(1)):
            return cc, "административная голова"

    for m in _LOC_ACC.finditer(tl):               # D-062D-2
        cc = _pl_resolve(m.group(1))
        if cc and cc not in others and not _pl_dependent(tl, m.start(1)):
            return cc, "винительный при предикате"

    for m in _LOC.finditer(tl):
        cc = _pl_resolve(m.group(1))
        if cc and cc not in others:
            if _pl_dependent(tl, m.start(1)):
                continue                          # D-058-2
            return cc, "локатив"

    for m in _LOC_PN.finditer(tl):                # D-062-2
        cc = _pl_resolve(m.group(1))
        if cc and cc not in others and not _pl_dependent(tl, m.start(1)):
            return cc, "локатив по/над"

    _actor_gen = set()
    for _am in _GEN_ACTOR.finditer(tl):
        _actor_gen.add(_am.start(1))
    for m in _GEN_HEAD.finditer(tl):              # D-062-1
        if _is_attributive(m.group(1)):           # D-065-1
            continue
        # Генитив после опоры удара, за которым следует «по <цель>»:
        # это актор, а не место события.
        if m.start(1) in _actor_gen:
            continue
        cc = _pl_resolve(m.group(1))
        if cc and cc not in others and not _pl_dependent(tl, m.start(1)):
            return cc, "генитив при опоре"
    # TASK-064E · опора и топоним разделены зависимыми словами:
    # «системы тепловых сетей Харькова». Прежняя ветка брала первое
    # совпадение _GEN_HEAD — опорой становилась «атаку», захватом предлог
    # «на», и до топонима поиск не доходил.
    # Допускается до двух промежуточных слов; список опор сужен до тех,
    # что доказаны на контрольных случаях, — «жители», «удар», «пожар»
    # сюда не входят, у них топоним стоит вплотную.
    # TASK-074 · R2. Окно после опоры проверяется потокенно слева направо:
    # берётся ПЕРВЫЙ резолвимый географический токен. Прежняя версия
    # захватывала последний токен окна — «сеть европы до предела» давала
    # «предела» вместо «европы».
    for m in re.finditer(r"(?:сет[ьи]\w*|систем\w*|облигац\w*|инфраструктур\w*|"
                         r"энергосистем\w*|электросет\w*)\s+((?:[а-яё\-]+\s+){0,2}[а-яё\-]+)",
                         tl, re.I):
        _win = m.group(1).split()
        _off = m.start(1)
        for _tok in _win:
            _p = tl.find(_tok, _off)
            _off = (_p + len(_tok)) if _p >= 0 else _off
            if _is_attributive(_tok):
                continue
            cc = _pl_resolve(_tok)
            if cc and cc not in others and not _pl_dependent(tl, max(_p, 0)):
                return cc, "генитив через зависимые"

    for m in _GENIT.finditer(tl):                 # D-058-1C
        cc = _pl_resolve(m.group(1))
        if cc and cc not in others:
            return cc, "географический генитив"

    for _part in (text or "").strip().split("\n"):
        _tm = _TAIL_GEO.search(_part.strip())     # TASK-065A
        if _tm:
            _pl = _places_in(_tm.group(1).lower())
            if _pl:
                _cc = _pl[0][1][0]
                if _cc not in others and not _is_attributive(_tm.group(1).split()[-1]):
                    return _cc, "страна в конце через тире"

    mm = _MIDDOT.match((title or "").strip())     # TASK-064A-R
    if mm:
        # правая часть — уточняющий объект, левая — макрозона
        for _part in (mm.group(2), mm.group(1)):
            _pl = _places_in(_part.lower())
            if _pl:
                _cc = _pl[0][1][0]
                if _cc not in others:
                    return _cc, "уточнение после точки"

    mc = _COLON.match((title or "").strip())      # D-058-1
    if mc:
        for part in (mc.group(1), mc.group(2)):
            pl = _places_in(part.lower())
            if pl:
                cc = pl[0][1][0]
                if cc not in others:
                    return cc, "двоеточие"

    for rx in (_APPOS, _APPOS2):                  # D-058-1B
        m = rx.search(title or "")
        if m:
            cc = _pl_resolve(m.group(1).lower())
            if cc and cc not in others:
                return cc, "приложение"

    return None, "места не названо"


def resolve_geo(title, summary='', raw_coords=None, domain=None):
    """ЕДИНСТВЕННЫЙ алгоритм гео-резолва (SINGLE SOURCE). → GeoContract."""
    # TASK-069 · интегрированный резолвер. Порядок веток в нём собственный
    # и не зависит от шестнадцати legacy-веток ниже: попытка встроить
    # конструкции между ними приводила к перехвату NATURAL и LOCATIVE
    # (TASK-068B). Legacy остаётся источником зон и координат.
    if GEO_V3:
        _v3blob = (str(title or '') + ' ' + str(summary or '')).lower()
        try:
            _v3cc, _v3src = detect_place_v2(title, summary, [])
        except Exception:
            _v3cc, _v3src = None, None
        if _v3cc:
            _v3g = None
            for _k, _v in GAZ.items():
                if _v[0] == _v3cc:
                    _v3g = _v; break
            if _v3g:
                return _mk(_v3g, _v3src, _v3blob, None, raw_coords)
        # v3 отказал — legacy-ветки НЕ добирают место. Их условия мягче
        # контракта: locative и natural дают страну без проверки физичности
        # действия, object и subject — по роли, запрещённой ADR-051.
        # Исключение — зоны и координаты: их v3 не вычисляет, они приходят
        # из legacy и не связаны с country.
        try:
            _lg = _resolve_geo_legacy(title, summary, raw_coords, domain)
        except Exception:
            _lg = None
        if _lg is not None and getattr(_lg, 'zone_id', None):
            return _lg
        # TASK-169: континент или макрорегион как зона. Проверяется ПОСЛЕ
        # страны и legacy-зон: конкретное место всегда приоритетнее.
        # «Лесные пожары в Европе» не имеет страны, но имеет континент.
        _rz = _region_zone(_v3blob)
        if _rz:
            return _mk_zone(_rz, 'регион', _v3blob, None, raw_coords, conf=0.7)
        if _lg is not None and _lg.country is None:
            return _lg
        return _NULL
    return _resolve_geo_legacy(title, summary, raw_coords, domain)


def _resolve_geo_legacy(title, summary='', raw_coords=None, domain=None):
    """Legacy-ветки. Источник зон и координат; country отдаёт только
    при GEO_V3=False."""
    try:
        t = str(title or '').strip().lower()
        s = str(summary or '').lower()
        blob = (t + ' ' + s)
        # ФИКС #3: «Украинск* ССР» — историческая отсылка (УССР 1922-1991), место
        # рождения ≠ современная Украина как актор/impact. Гасим до gazetteer.
        blob = re.sub(r'украинск\w*\s+сср', ' советск-респ ', blob)
        # Британская Колумбия — провинция Канады (не GB через стем 'британ'). Явное сопоставление до gazetteer (покрывает падежи).
        if re.search(r'британск\w*\s+колумби', blob):
            return _mk(('CA','Канада',53.7,-127.6),'natural',blob,None,raw_coords)
        # opinion/advertorial-гейт: лучше скрыть, чем неверно
        if _OPINION_T.match(t) or _ADVERT.search(s):
            return _NULL
        # actor-detect: место в первом слове + кинетика в начале заголовка = актор, не точка
        actor = None
        mm = re.match(r'\s*([а-яё\-]+)', t)
        if mm:
            ap = _place_at(mm.group(1))
            # оборонительная кинетика («сбил/перехватил/отразил») = событие у себя,
            # первое слово — место процесса, а не актор
            _defensive = re.search(r'(сбил|сбит|перехват|отразил|отбил)', t[:90])
            # субъектное действие: «Страна + глагол» в начале — подлежащее является
            # актором, а не местом (место придёт из локатива дальше по тексту)
            _subj_verb = re.match(r'\s*[а-яё\-]+\s+(?:начал|нач[аёе]|заявил|обвин|отказал|идентифиц|прекрат|потребова|пригроз|объявил|решил|ввел|ввёл|закупа|планир|namерен|намерен)', t)
            if ap and (_KIN.search(t[:90]) or _subj_verb) and not _defensive:
                actor = ap[0]
                # субъектное действие: если в ЗАГОЛОВКЕ нет локатива «в X» (места-цели),
                # процесс происходит у субъекта — он и место, актора нет
                if _subj_verb and not re.search(r'(?:^|[^а-яё])(?:в|во|на)\s+[а-яё]', t):
                    _sp = _place_at(mm.group(1))
                    if _sp:
                        return _mk(_sp, 'subject', blob, None, raw_coords)
        # STATEMENT: заявление/цитата без кинетики/природы → нет точки (упоминания сохраняем)
        if _STMT.search(t) and not _KIN.search(blob) and not _NAT.search(blob):
            return _null_mentions(blob, actor)
        # цитатный заголовок = мнение/оценка: событийность считаем по заголовку,
        # упоминание прошлых атак в summary не делает цитату событием
        if t[:1] in ('«', '"', "'", '\u2018', '\u201c') and not _KIN.search(t) and not _NAT.search(t):
            return _null_mentions(blob, actor)
        # OBJECT-BOUND: «объект … в X»
        for m in re.finditer(_OBJ + r'[^.]{0,30}?(?:^|[^а-яё])(?:в|во|на)\s+([а-яё\-]+)', blob, re.I):
            p = _place_at(m.group(1))
            if p and p[0] != actor:
                return _mk(p, 'object', blob, actor, raw_coords)
        # DIRECTION: «на юге X»
        for m in re.finditer(r'(?:на|в)\s+(?:юге|севере|западе|востоке|центре)\s+([а-яё\-]+)', blob, re.I):
            p = _place_at(m.group(1))
            if p and p[0] != actor:
                return _mk(p, 'direction', blob, actor, raw_coords)
        # KINETIC-TARGET: «удар … по X» (кроме не-мест: «по военным объектам»)
        # Морская цель — не страна флага. «Удар по танкеру из ОАЭ … при
        # прохождении через Ормузский пролив» давал ОАЭ: kinetic_target
        # стоит выше ZONE-EXPLICIT и забирал страну принадлежности судна.
        # Судно находится там, где акватория, поэтому при морской цели
        # ветка пропускается — ниже сработает зона.
        _sea_target = bool(re.search(r'по\s+(?:[а-яё\-]+\s+){0,2}'
                                     r'(судн\w*|танкер\w*|корабл\w*|сухогруз\w*|балкер\w*|'
                                     r'контейнеровоз\w*|катер\w*|траулер\w*|паром\w*)', blob, re.I))
        _sea_zone = _sea_target and any(rx.search(blob) for rx, _z in _ZONE_GAZ)
        if _KIN.search(blob) and not _sea_zone:
            _kt_re = (r'(?:^|[^а-яё])по\s+([а-яё\-]+(?:\s+[а-яё\-]+){0,2})'
                      if GEO_ACTOR_TARGET_CANARY else
                      r'(?:^|[^а-яё])по\s+([а-яё\-]+(?:\s+[а-яё\-]+)?)')
            for m in re.finditer(_kt_re, blob, re.I):
                parts = m.group(1).split()
                if _NONP.search(m.group(0)):
                    # ACTOR-TARGET: «по военным объектам X» — genitive-цель ПОСЛЕ объекта =
                    # место удара (не страна-инициатор). Дотягиваемся до цели за bad-span.
                    if GEO_ACTOR_TARGET_CANARY and len(parts) >= 2:
                        p = _place_at(parts[-1])
                        if p and p[0] != actor:
                            return _mk(p, 'kinetic_target', blob, actor, raw_coords)
                    continue
                p = _place_at(parts[-1]) or _place_at(parts[0])
                if p and p[0] != actor:
                    return _mk(p, 'kinetic_target', blob, actor, raw_coords)
        # ZONE-EXPLICIT: акватория/пролив/полярная зона/возд.пространство названы местом
        # процесса → зона, НЕ ближайшее государство (Zone Layer).
        # Зона из заголовка — всегда; из summary — только при событийном контексте
        # (кинетика/природа/outage/морская лексика), иначе политические тексты
        # с упоминанием акваторий дают ложные зоны
        # TASK-048: ZONE-EXPLICIT видит полный текст независимо от того,
        # урезан ли blob вызывающей стороной. Условие _zone_evt сохранено.
        _zblob = _ZONE_FULLTEXT or blob
        _zone_evt = bool(_KIN.search(_zblob) or _NAT.search(_zblob) or _OUTAGE.search(_zblob)
                         or re.search(r'судн|танкер|корабл|флот|вмс|патрул|конво', t))
        # Выбор по позиции в тексте, а не по порядку в _ZONE_GAZ.
        # «Атака на Моку на Красном море. Тем временем Иран заявил, что
        # Ормузский пролив открыт» давала Ормуз: он стоит в справочнике
        # выше, хотя упомянут позже и к событию не относится.
        _zc = []
        for rx, zid in _ZONE_GAZ:
            _m = rx.search(t)
            if _m:
                _zc.append((_m.start(), 0, zid))      # заголовок приоритетнее
            elif _zone_evt:
                _m = rx.search(_zblob)
                if _m:
                    _zc.append((_m.start(), 1, zid))
        if _zc:
            _zc.sort(key=lambda x: (x[1], x[0]))
            return _mk_zone(_zc[0][2], 'zone', blob, actor, raw_coords)
        # GLOBAL: планетарные процессы без территории
        if _GLOBAL_RX.search(blob):
            return _mk_zone('global', 'global', blob, actor, raw_coords, conf=0.8)
        # bad spans: «по военным…» и атрибутивные прилагательные («российский дрон»)
        bad = [(m.start(), m.end()) for m in _NONP.finditer(blob)]
        bad += [(m.start(), m.end()) for m in _ATTADJ.finditer(blob)]
        # NATURAL
        if _NAT.search(blob):
            pl = _places_in(blob, excl=actor, bad=bad)
            if pl:
                return _mk(pl[0][1], 'natural', blob, actor, raw_coords)
        # OUTAGE
        if _OUTAGE.search(t):
            pl = _places_in(blob, excl=actor, bad=bad)
            if pl:
                return _mk(pl[0][1], 'outage', blob, actor, raw_coords)
        # CURRENCY (рубль → RU)
        if _CURR.search(t):
            return _mk(GAZ['росс'], 'currency', blob, actor, raw_coords)
        # NO-GEO гейт (упоминания сохраняем)
        if _NOGEO.search(blob) and not _KIN.search(blob):
            return _null_mentions(blob, actor)
        # LOCATIVE: ближайший к якорю (объект/кинетика/природа)
        anchors = [m.start() for rx in (re.compile(_OBJ, re.I), _KIN, _NAT)
                   for m in rx.finditer(blob)]
        cand = []
        for m in re.finditer(r'(?:^|[^а-яё])' + _LOCP + r'\s+([а-яё\-]+)', blob, re.I):
            _wpos = m.start(1)
            if any(b[0] - 1 <= _wpos < b[1] for b in bad):
                continue                     # «на украинского миллиардера» — атрибутив, не место
            p = _place_at(m.group(1))
            if p and p[0] != actor:
                d = min((abs(m.start() - a) for a in anchors), default=m.start())
                cand.append((d, m.start(), p))
        if cand:
            cand.sort(key=lambda x: (x[0], x[1]))
            return _mk(cand[0][2], 'locative', blob, actor, raw_coords)
        # ADJ-LOCATIVE: «в немецком Штаде» — национальное прилагательное задаёт страну
        _ADJ_CC = {'немецк': 'герман', 'германск': 'герман', 'французск': 'франци',
                   'итальянск': 'итали', 'испанск': 'испани', 'американск': 'сша',
                   'британск': 'британ', 'польск': 'польш', 'турецк': 'турци',
                   'японск': 'япони', 'китайск': 'китай', 'индийск': 'инди',
                   'украинск': 'украин', 'российск': 'росс', 'иранск': 'иран',
                   'израильск': 'израил', 'чешск': 'чехи', 'австрийск': 'австри',
                   'швейцарск': 'швейцари', 'бельгийск': 'бельги', 'шведск': 'швеци',
                   'норвежск': 'норвеги', 'финск': 'финлянд', 'греческ': 'греци'}
        m_adj = re.search(r'(?:^|[^а-яё])(?:в|во|на)\s+([а-яё]+)(?:ом|ой|ом)\s+[а-яё\-]', blob)
        if m_adj:
            for _adj, _stem in _ADJ_CC.items():
                if m_adj.group(1).startswith(_adj):
                    return _mk(GAZ[_stem], 'adj_locative', blob, actor, raw_coords)
        # SINGLE: единственное место в тексте.
        # ADR-051 запрещает как источник PLACE: ветка берёт страну
        # независимо от роли и даёт место 75 событиям, у которых его
        # быть не должно (TASK-068D). Снимается вместе с включением
        # интегрированного резолвера, не раньше.
        if not GEO_V3:
            pl = _places_in(blob, excl=actor, bad=bad)
            if len(pl) == 1:
                return _mk(pl[0][1], 'single', blob, actor, raw_coords)
        # ZONE-COORDS: природный процесс без страны, координаты над известным
        # бассейном → зона по координатам (порт _seaBasin; не привязываем к суше)
        if raw_coords and (_NAT.search(blob) or domain == 'climate'):
            try:
                rla, rln = float(raw_coords[0]), float(raw_coords[1])
                # CONUS guard (Lever B, data): суша континентальных США не
                # зонируется как океан/бассейн (bbox pacific_ocean через антимеридиан
                # покрывает запад США) → резолвим в США с сохранением координаты.
                if 24.0 <= rla <= 49.5 and -125.0 <= rln <= -66.0:
                    return _mk(GAZ['сша'], 'natural', blob, actor, (rla, rln))
                for zid in _BASIN_IDS:
                    zbox = ZONES[zid][4]
                    if _zone_contains(zbox, rla, rln):
                        return _mk_zone(zid, 'zone_coords', blob, actor, (rla, rln), conf=0.75)
            except (TypeError, ValueError):
                pass
        return _null_mentions(blob, actor)
    except Exception:
        return _NULL


