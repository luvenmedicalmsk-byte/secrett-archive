# GEO CONSISTENCY GATE
# ══════════════════════════════════════════════════════════════════════════════
def validate_geo(gc):
    """Consistency-gate перед публикацией. → (ok:bool, errors:list[str])."""
    errs = []
    if not isinstance(gc, GeoContract):
        return False, ['not_a_contract']
    if gc.precision not in VALID_PRECISION:
        errs.append('bad_precision:%s' % gc.precision)
    if not (0.0 <= (gc.confidence or 0.0) <= 1.0):
        errs.append('bad_confidence:%s' % gc.confidence)
    if gc.process_place_type not in (None, 'country', 'zone', 'global'):
        errs.append('bad_place_type:%s' % gc.process_place_type)
    if gc.process_place_type in ('zone', 'global'):
        # зона: страна отсутствует, zone_id валиден, координаты внутри границ зоны
        if gc.country is not None:
            errs.append('zone_with_country')
        if gc.zone_id not in ZONES:
            errs.append('unknown_zone:%s' % gc.zone_id)
        else:
            _n, _zt, _zla, _zln, _zbox = ZONES[gc.zone_id]
            if gc.zone_type != _zt:
                errs.append('zone_type_mismatch')
            if gc.lat is not None and _zbox and not _zone_contains(
                    (_zbox[0] - 1.5, _zbox[1] + 1.5, _zbox[2] - 1.5, _zbox[3] + 1.5),
                    gc.lat, gc.lng):
                errs.append('coords_outside_zone')
            if not gc.region:
                errs.append('empty_region')
        return (not errs), errs
    if gc.process_place_type == 'country' and gc.country is None:
        errs.append('country_type_without_country')
    if gc.country is None:
        if gc.lat is not None or gc.lng is not None:
            errs.append('coords_without_country')
        if gc.precision != 'none':
            errs.append('precision_without_country')
    else:
        if gc.lat is None or gc.lng is None:
            errs.append('country_without_coords')
        elif gc.country in BBOX and not in_bbox(gc.country, gc.lat, gc.lng, margin=1.5):
            errs.append('coords_outside_country')
        if not gc.region:
            errs.append('empty_region')
        if gc.actor_country and gc.actor_country == gc.country and gc.source in (
                'object', 'direction', 'kinetic_target'):
            errs.append('actor_as_map_point')
        if gc.actor_country and gc.actor_country in gc.impact_countries:
            errs.append('actor_in_impact')
    return (not errs), errs
