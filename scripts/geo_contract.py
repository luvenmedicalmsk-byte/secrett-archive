# потому что вне физического контекста те же предлоги означают тему
# («заявила по Одессе») или обсуждение («над Белгородом обсуждали»).
_LOC_PN = re.compile(r"(?:^|[^а-яё])(?:по|над)\s+([а-яё\-]+)", re.I)
# D-062-1 · генитив без предлога: «Жители X», «Обстрел X», «Атака на X».
# Требуется опорное существительное, иначе любая страна в родительном
# падеже стала бы местом.
# D-065-1 · географическое ПРИЛАГАТЕЛЬНОЕ после опоры обозначает
# принадлежность, а не место: «ударов украинских дронов» — дроны
# украинские, но удар пришёлся по России, названной отдельно.
# Существительное в родительном («обстрел Белгорода», «пожары Греции»)
# место обозначает и под гейт не подпадает.
_GEO_ADJ = re.compile(r"(?:ск|цк)(?:ий|ая|ое|ые|ие|ого|ой|их|им|ими|ом|ую)$", re.I)


def _is_attributive(word):
    """Прилагательное = принадлежность, не место события."""
    return bool(_GEO_ADJ.search(word or ""))


_GEN_HEAD = re.compile(r"(?:жител\w*|населен\w*|обстрел\w*|бомбардировк\w*|"
                       r"атак\w*|удар\w*|взрыв\w*|пожар\w*|наводнен\w*|"
                       r"окраин\w*|пригород\w*|центр\w*|улиц\w*)\s+([а-яё\-]+)", re.I)
_TGT_P = re.compile(r"(?:удар\w*|атак\w*|обстрел\w*)\s*(?:по|на)\s+([а-яё\-]+)", re.I)

# D-058-1 · «EVENT : LOCATION» и «LOCATION : EVENT»
_COLON = re.compile(r"^([^:]{2,40}):\s*(.+)$")
# TASK-064A-R · «Пожарный сигнал — Европа · Катания».
# Правая часть после «·» уточняет левую макрозону, поэтому проверяется
# ПЕРВОЙ: конкретный объект точнее континента. Разделитель «·» обязателен —
# без него конструкция не отличима от обычного заголовка с тире.
# TASK-068G · outage как содержание сообщения, а не событие.
_OUT_CONTENT = re.compile(r"\b(?:о|об|про)\s+(?:[а-яё]+\s+){0,2}"
                          r"(?:отключени|падени|блэкаут|блекаут|сбо[еи]|обесточ)", re.I)
_MIDDOT = re.compile(r"^(.{2,60}?)\s*[·•]\s*(.{2,40})$")
# TASK-065A · «… — Страна» в КОНЦЕ текста. Источники ставят страну
# события через тире в конце описания: «…нефтеперерабатывающему заводу
# — Россия». Ветка работает по всему тексту, а не только по заголовку,
# и требует, чтобы после тире стояло 1-3 слова до конца строки —
# иначе тире внутри предложения давало бы ложные срабатывания.
_TAIL_GEO = re.compile(r"[—–]\s*([а-яёa-z\-]+(?:\s+[а-яёa-z\-]+){0,2})\s*$", re.I)
# D-058-1B · приложение: «в Виотии, Греция» / «Греция, Виотия:»
# «в REGION, COUNTRY» — приложение уточняет регион. Регистр не проверяется:
# признаком служит позиция после запятой сразу за локативной группой,
# а не заглавная буква. Страна должна резолвиться — иначе не приложение.
_APPOS = re.compile(r"(?:^|[^а-яё])(?:в|во|на)\s+[а-яёa-z\-]+,\s*([а-яёa-z\-]{3,})", re.I)
# D-062C-1 · «в муниципалитете X», «в регионе X» — административная голова
# из ограниченного набора, за ней географический объект. Произвольное слово
# головой не считается: иначе «в результате X» дало бы место.
_ADMIN_HEAD = re.compile(r"(?:^|[^а-яё])(?:в|во|на)\s+"
                         r"(?:муниципалитет\w*|район\w*|област\w*|провинци\w*|регион\w*)\s+"
                         r"([а-яёa-z\-]+)", re.I)
_APPOS2 = re.compile(r"^([а-яёa-z\-]{3,}),\s*[а-яёa-z\-]+\s*:", re.I)
# D-058-1C · географический указатель + родительный
# Порядок альтернатив значим: составные указатели («центральной части»,
# «северной части») стоят ПЕРВЫМИ, иначе «центр\w*» поглощает прилагательное
# и в захват попадает «части» вместо страны.
_GENIT = re.compile(r"(?:^|[^а-яё])(?:в|во|на)\s+"
                    r"(?:(?:северн|южн|восточн|западн|центральн)\w*\s+част\w*|"
                    r"северо-восток\w*|северо-запад\w*|юго-восток\w*|юго-запад\w*|"
                    r"север\w*|юг\w*|восток\w*|запад\w*|центр\w*)\s+"
                    r"([а-яё\-]+)", re.I)
# D-058-2 · зависимое действие: локатив принадлежит не событию
_DEPEND = re.compile(r"(произв[её]д\w*|изготовл\w*|разработ\w*|собран\w*|создан\w*|"
                     r"происход\w*|поставщик\w*)\s+в$", re.I)


