def detect_third_party(text, actors, targets, others, place):
    """THIRD_PARTY[] · стороны, затронутые событием косвенно."""
    tl = (text or "").lower()
    _scope = _main_clause(tl)
    # 101 · при каузальной конструкции затронутая сторона стоит ПЕРЕД предикатом.
    _cz = _CAUSAL_PRED.search(_scope)
    if _cz:
        _head = _scope[:_cz.start()]
        if not G._places_in(_head):
            _mt = re.search(r"\s(?:на|по)\s+([а-яё\-]+)\s*$", _scope[_cz.end():].rstrip())
            if _mt:
                _head = _mt.group(1)
        _out = []
        for _p, _g in G._places_in(_head):
            _cc = _g[0]
            if _cc in actors or _cc in targets or _cc in others:
                continue
            if _cc not in _out:
                _out.append(_cc)
        return _out
    m = _TP_PRED.search(_scope)
    if not m:
        return []
    # Затронутая сторона может стоять ВНУТРИ совпадения предиката:
    # «оставил X без Y», «по X нанесён удар». Хвост берётся от начала
    # именной группы, а не от конца всего совпадения.
    _sp = re.match(r"(остав\w+)\s+", m.group(0), re.I)
    if _sp:
        tail = tl[m.start() + _sp.end():]
    elif re.match(r"по\s+", m.group(0), re.I):
        tail = tl[m.start() + 3:]
    else:
        tail = tl[m.end():]
    _excl = _tail_excluded(tail, _spo_subject(text))
    out = []
    for _pos, _g in G._places_in(tail):
        cc = _g[0]
        if cc in actors or cc in targets or cc in others:
            continue
        if cc in _excl:
            continue
        if cc not in out:
            out.append(cc)
    return out
