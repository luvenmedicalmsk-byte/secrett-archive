_BARE_RX = {c: re.compile(r'\b' + c[:-1] + r'[а-яё]{0,3}\b', re.I) for c in BARE_CITY_SUBJECT}


def all_subjects(text):
    """ВСЕ субъекты, упомянутые в тексте. Событие «атакованы склады в Тамбовской
    области и в Электростали» относится к двум регионам сразу — одного места мало."""
    low = (text or '').lower()
    out = []
    for stem, name in RU_SUBJECTS.items():
        if stem in low and stem not in SPB_DISTRICT_HOMONYMS and name not in out:
            out.append(name)
    for c, nm in BARE_CITY_SUBJECT.items():
        if _BARE_RX[c].search(low) and nm not in out:
            out.append(nm)
    if ('петербург' in low or 'спб' in low) and 'Санкт-Петербург' not in out:
        out.append('Санкт-Петербург')
    return out


def ru_subject(text):
    """Каноничное имя субъекта РФ, если он явно упомянут в тексте, иначе None."""
    if not text or not isinstance(text, str):
        return None
    low = text.lower()
    # GEO-fix: районы СПб (Кировский, Московский, Приморский, Невский…) носят имена
    # одноимённых субъектов — "удар в Кировском районе Санкт-Петербурга" резолвился
    # в "Кировскую область" (снос 1200 км). Поэтому Петербург выигрывает у ОМОНИМОВ
    # своих районов.
    # GEO-fix-2: но guard был безусловным и перебивал субъект, названный в заголовке:
    # "В Ленинградской области пожар на складах WB" + упоминание Петербурга в теле
    # текста давало регион "Санкт-Петербург". Теперь неомонимичный субъект побеждает,
    # если упомянут РАНЬШЕ Петербурга.
    _BIG = 10 ** 9
    _p_spb = min([low.find(x) for x in ('петербург', 'спб') if x in low] or [_BIG])
    _cand = [(low.find(stem), name) for stem, name in RU_SUBJECTS.items()
             if stem in low and stem not in SPB_DISTRICT_HOMONYMS]
    for _c, _nm in BARE_CITY_SUBJECT.items():
        _m = _BARE_RX[_c].search(low)
        if _m:
            _cand.append((_m.start(), _nm))
    if _cand:
        _pos, _name = min(_cand)
        if _pos <= _p_spb:
            return _name
    if _p_spb < _BIG:
        return 'Санкт-Петербург'
    if 'севастопол' in low:
        return 'Севастополь'
    for stem, name in RU_SUBJECTS.items():
        if stem in low:
            return name
    return None


def is_ru_text(text):
    """True, если в тексте есть надёжный маркер России (субъект или нацорган)."""
    if not text or not isinstance(text, str):
        return False
    low = text.lower()
    return any(tok in low for tok in RU_COUNTRY_TOKENS)

# Бэйр-города РФ (именительный падеж), которых нет среди -ск стемов RU_SUBJECTS.
_RU_BARE_CITIES = ('белгород', 'воронеж', 'ростов', 'краснодар')

def ru_place_in_title(title):
    """True, если в ЗАГОЛОВКЕ явный RU-топоним (субъект РФ или однозначный город).
    Fallback: primary=RU, когда основной резолвер оставил primary пустым. RU-топоним —
    всегда МЕСТО события, а не актор ("украинская ракета над Удмуртией" -> локация RU).
    Проверяется только заголовок (не summary), чтобы упоминания вроде "москвичей" в
    описании не давали ложную РФ-атрибуцию европейским событиям."""
    if not title or not isinstance(title, str):
        return False
    low = title.lower()
    if ru_subject(low):
        return True
    return any(c in low for c in _RU_BARE_CITIES)


