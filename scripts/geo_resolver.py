# Полный список стемов для детекции страны RU (субъекты + маркеры). ОДИН источник.
RU_COUNTRY_TOKENS = sorted(set(list(RU_SUBJECTS.keys()) + RU_EXTRA_MARKERS))


def ru_subject(text):
    """Каноничное имя субъекта РФ, если он явно упомянут в тексте, иначе None."""
    if not text or not isinstance(text, str):
        return None
    low = text.lower()
    for stem, name in RU_SUBJECTS.items():
        if stem in low:
            return name
    return None


def is_ru_text(text):
    """True, если в тексте есть надёжный маркер России (субъект или нацорган)."""
    if not text or not isinstance(text, str):
        return False
    low = text.lower()
    return any(tok in low for tok in RU_COUNTRY_TOKENS)
