# Стоп-слова: стемы, которые встречаются внутри обычных слов и дают ложный матч.
# (граница слова + эти исключения; напр. 'итали' внутри 'капитализация')
_FC_GUARD = {
    'итали': ('капитал',),
    'кита': ('никита', 'архитек'),
    'иран': ('стиран', 'тиран', 'иранир'),
    'кубе': ('кубер', 'инкуб'),
    'чили': ('чилийск', 'чили con', 'перец чили', 'чили кон'),  # чилийский перец != Чили
    'перу': ('перуш', 'перуан нет'),
    'судан': ('суданов',),  # судановый краситель != Судан
}

_PRIORITY_GEO = {
    'монако': ('MC', 'Монако'), 'лихтенштейн': ('LI', 'Лихтенштейн'),
    'сан-марино': ('SM', 'Сан-Марино'), 'андорр': ('AD', 'Андорра'), 'ватикан': ('VA', 'Ватикан'),
    'люксембург': ('LU', 'Люксембург'), 'мальт': ('MT', 'Мальта'), 'исланди': ('IS', 'Исландия'),
    'флорид': ('US', 'США'), 'техас': ('US', 'США'), 'калифорни': ('US', 'США'),
}

def foreign_country(text):
    """V6.5: (ISO2, рус.имя) иностранного государства по тексту, матч по началу слова.
    Возвращает (cc, name) или (None, None). РФ здесь НЕ резолвится (см. ru_subject)."""
    if not text or not isinstance(text, str):
        return (None, None)
    low = text.lower()
    # Калифорнийский залив = мексиканские воды (не штат Калифорния); явное упоминание Мексики приоритетно
    if 'калифорнийск' in low and ('залив' in low or 'мексик' in low):
        return ('MX', 'Мексика')
    if _re.search(r'(?<![а-яёa-z])мексик', low) and _re.search(r'(?<![а-яёa-z])калифорни', low):
        return ('MX', 'Мексика')
    for stem, (cc, name) in _PRIORITY_GEO.items():
        if _re.search(r'(?<![а-яёa-z])' + _re.escape(stem), low):
            return (cc, name)
    for stem, (cc, name) in FOREIGN_COUNTRIES.items():
        # матч только в начале слова: граница слева
        if _re.search(r'(?<![а-яёa-z])' + _re.escape(stem), low):
            # защита от ложных подстрок внутри длинных слов
            guard = _FC_GUARD.get(stem)
            if guard:
                # если стем сидит внутри запретного слова -> пропускаем
                bad = False
                for g in guard:
                    if _re.search(r'(?<![а-яёa-z])' + _re.escape(g), low) and stem in g:
                        bad = True; break
                if bad:
                    continue
            return (cc, name)
    return (None, None)
