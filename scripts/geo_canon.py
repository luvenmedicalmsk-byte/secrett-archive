# ══════════════════════════════════════════════════════════════════════════════
# ПУБЛИЧНЫЙ API — единственный интерфейс к канонической географии.
# ══════════════════════════════════════════════════════════════════════════════

def by_iso(iso2):
    """Каноническая запись по ISO2. None, если неизвестно."""
    return GEO_CANON.get((iso2 or '').upper())


def continent(iso2):
    """Список континентов страны (для трансконтинентальных — несколько)."""
    r = by_iso(iso2)
    return r['continent'] if r else []


def is_transcontinental(iso2):
    r = by_iso(iso2)
    return bool(r and r['transcontinental'])


def macro_region(iso2):
    r = by_iso(iso2)
    return r['macro_region'] if r else None


def center(iso2):
    r = by_iso(iso2)
    return r['center'] if r else None


def resolve(text):
    """Резолв ISO2 из произвольного текста/названия по алиасам. None, если нет."""
    t = (text or '').strip().lower()
    if not t:
        return None
    if t in _ALIAS_INDEX:
        return _ALIAS_INDEX[t]
    for _a, _iso in _ALIAS_INDEX.items():
        if len(_a) >= 4 and _a in t:
            return _iso
    return None


def ru_subregion_continent(region_text):
    """Континент российского субрегиона ('EU'/'AS'). None, если не распознан
    как рос.субрегион. Устраняет дефект 'азиатская Россия → Европа'."""
    t = (region_text or '').lower()
    for stem, cont in RU_SUBREGION_CONTINENT.items():
        if stem in t:
            return cont
    return None


def macro_info(name):
    """Инфо о макрорегионе (continent, is_container). None, если не макро."""
    return MACRO_REGIONS.get(name)


def is_container(place_name):
    """True, если place — макрорегион-контейнер (нельзя использовать как
    process_place для события в конкретной стране; должен резолвиться до страны)."""
    m = MACRO_REGIONS.get(place_name)
    return bool(m and m.get('is_container'))


def zone_info(name):
    return ZONES.get(name)


def same_continent(iso_list, ignore_transcontinental=True):
    """True, если все страны списка на одном континенте. Трансконтинентальные
    (RU/TR/KZ) по умолчанию не нарушают (совместимы с любым их континентом)."""
    conts = []
    for iso in iso_list or []:
        r = by_iso(iso)
        if not r:
            continue
        if ignore_transcontinental and r['transcontinental']:
            continue
        conts.append(set(r['continent']))
    if not conts:
        return True
    common = set.intersection(*conts) if len(conts) > 1 else conts[0]
    return bool(common)


