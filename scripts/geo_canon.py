def resolve_place(text):
    """Универсальный резолв: страна(ISO2) | континент | макрорегион | зона.
    Возвращает dict {'type', 'code'/'name'} или None. Единая точка входа для потребителей."""
    t = (text or '').strip()
    if not t:
        return None
    iso = resolve(t)
    if iso:
        return {'type': 'country', 'code': iso}
    if t in MACRO_REGIONS:
        return {'type': 'macro', 'name': t}
    cru = continent_name_ru(t)
    if cru:
        return {'type': 'continent', 'name': cru}
    return None

