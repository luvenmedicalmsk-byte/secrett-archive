def gaz_entry(stem):
    """Полная GAZ-запись (iso, display_name, lat, lng) по стему — единый источник
    для резолвера вместо независимого geo_contract.GAZ."""
    iso = GAZ_ALIASES.get(stem)
    if not iso:
        return None
    lat, lng = GAZ_COORDS.get(stem, (None, None))
    return (iso, GAZ_NAMES.get(stem, (by_iso(iso) or {}).get('name_ru', iso)), lat, lng)


def build_gaz():
    """Реконструкция полного словаря GAZ из канона (для миграции резолвера)."""
    return {stem: gaz_entry(stem) for stem in GAZ_ALIASES}

