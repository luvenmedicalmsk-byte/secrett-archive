    for iso, r in GEO_CANON.items():
        out[iso] = {'ru': r['name_ru'], 'en': r['name_en'], 'iso3': r['iso3'],
                    'gen': GENITIVE.get(iso), 'macro': r['macro_region'],
                    'radar_macro': RADAR_MACRO.get(iso, ''), 'continent': r['continent']}
    return out
